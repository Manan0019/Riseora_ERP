import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'riseora-115-'));
process.env.RISEORA_DB_PATH=path.join(tmp,'test.db');
process.env.RISEORA_BACKUP_DIR=path.join(tmp,'backups');
process.env.INITIAL_ADMIN_USERNAME='testadmin';
process.env.INITIAL_ADMIN_PASSWORD=`T${crypto.randomBytes(20).toString('hex')}`;
let db;
try {
  ({default:db}=await import('../src/db/database.js'));
  const {initDatabase}=await import('../src/db/initDatabase.js');
  await initDatabase();
  const {recordHistory,databaseHealth,monthlyActivity,formulaPlan,recordedLots}=await import('../src/services/proWorkspaceService.js');
  const {searchWorkspace}=await import('../src/services/workspaceSearchService.js');
  const {backupSchedule,setBackupSchedule}=await import('../src/services/backupScheduleService.js');
  const item=db.prepare('SELECT id,name FROM items ORDER BY id LIMIT 1').get();
  db.prepare('UPDATE items SET name=? WHERE id=?').run('V115 UNIQUE TEST ITEM',item.id);
  assert.ok(searchWorkspace('V115 UNIQUE TEST').some(r=>r.path===`/items?record=${item.id}`));
  assert.equal(recordHistory('items',item.id)[0].operation,'UPDATE');
  assert.equal(JSON.parse(recordHistory('items',item.id)[0].after_json).name,'V115 UNIQUE TEST ITEM');
  assert.equal(databaseHealth().quick,'ok');
  assert.equal(monthlyActivity().length,6);
  const raw=db.prepare("SELECT i.id,i.base_unit_id,u.code FROM items i JOIN units u ON u.id=i.base_unit_id WHERE u.code IN ('ML','L','G','KG') LIMIT 1").get();
  const other=db.prepare("SELECT id,code FROM units WHERE code=?").get(['ML','L'].includes(raw.code)?'G':'ML');
  db.prepare('UPDATE items SET density=1.25 WHERE id=?').run(raw.id);
  const formulaId=Number(db.prepare('INSERT INTO formulas(code,name,finished_item_id,version_no,batch_size,batch_unit_id) VALUES(?,?,?,?,?,?)').run('V115-TEST','Test plan',raw.id,1,100,raw.base_unit_id).lastInsertRowid);
  db.prepare('INSERT INTO formula_items(formula_id,ingredient_item_id,quantity,unit_id) VALUES(?,?,?,?)').run(formulaId,raw.id,10,other.id);
  const plan=formulaPlan(formulaId,200);
  assert.equal(plan.rows.length,1);
  const expected=raw.code==='ML'?16:raw.code==='L'?0.016:raw.code==='G'?25:0.025;
  assert.ok(Math.abs(plan.rows[0].required-expected)<1e-8);
  assert.equal(recordedLots(raw.id).physical,0);
  assert.equal(plan.total,null,'Unknown average cost must not be treated as zero');
  assert.deepEqual(backupSchedule(),{hours:24});
  assert.deepEqual(setBackupSchedule(6),{hours:6});
  assert.deepEqual(backupSchedule(),{hours:6});
  assert.throws(()=>setBackupSchedule(1));
  console.log('PASS v1.1.5 isolated database search, history, health, monthly activity and backup preference');
} finally {db?.close();fs.rmSync(tmp,{recursive:true,force:true});}
